#Write a program to input 2 number and print their sum, difference, product and quotient.

num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))

sum = num1 + num2 
diff = num1 - num2
product = num1 * num2
quotient = num1 / num2

print("sum is : ", sum)
print("difference is : ", diff)
print("product is : ", product)
print("quotient is : ", quotient)

